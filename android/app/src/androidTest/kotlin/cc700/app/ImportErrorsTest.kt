/**
 * Import errors in the real Compose pane (brief WP6): every invalid row of V§4 is pasted and validated,
 * and the pane must show the readable message naming the field and position, and offer no Save.
 * Generated by tools/android/gen_import_cases.py from android/core/src/test/resources/vectors.json.
 */
@RunWith(AndroidJUnit4::class)
class ImportErrorsTest {
    @get:Rule val rule = createComposeRule()

    class Case(val name: String, val text: String, val code: String, val path: String)

    private fun validate(text: String) {
        rule.onNodeWithTag("workout-text").performTextClearance()
        rule.onNodeWithTag("workout-text").performTextInput(text)
        rule.onNodeWithTag("validate").performClick()
    }

    private fun count(tag: String) = rule.onAllNodes(hasTestTag(tag)).fetchSemanticsNodes().size

    @Test fun everyInvalidRowShowsItsMessage() {
        var saved: Any? = null
        rule.setContent { CcTheme { WorkoutImportPane(ftp = 250) { saved = it } } }
        for (c in CASES) {
            validate(c.text)
            rule.onNodeWithTag("import-error").assertIsDisplayed().assertTextEquals(describe(c.code, c.path))
            assertEquals(c.name, 0, count("save"))
        }
        assertNull(saved)
    }

    @Test fun typographyIsNormalisedNotCorrected() {
        var saved: Any? = null
        rule.setContent { CcTheme { WorkoutImportPane(ftp = 250) { saved = it } } }
        // curly quotes and a non-breaking space: accepted after normalisation
        validate("{\u201cv\u201d: 1, \u201cname\u201d: \u201cSweet\u00a0spot\u201d, \u201csteps\u201d: " +
            "[{\u201clabel\u201d: \u201cSS\u201d, \u201csecs\u201d: 600, \u201cftp_pct\u201d: 90}]}")
        rule.onNodeWithTag("preview").assertIsDisplayed()
        rule.onNodeWithTag("save").performClick()
        assertNotNull(saved)
        // a label that is too long is reported, never shortened
        validate("""{"v": 1, "name": "t", "steps": [{"label": "Seventeen chars!!", "secs": 60, "ftp_pct": 50}]}""")
        rule.onNodeWithTag("import-error").assertTextEquals(describe("E_LABEL", "/steps/0/label"))
    }

    @Test fun w1Previews() {
        rule.setContent { CcTheme { WorkoutImportPane(ftp = 250, initial = W1) {} } }
        rule.onNodeWithTag("preview").assertIsDisplayed()
    }

