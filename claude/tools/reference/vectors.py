def reassemble(pkts):
    out = b''
    for i, p in enumerate(pkts):
        h = p[0]
        assert bool(h & 0x80) == (i == 0) and (h & 0x3F) == (i & 0x3F)
        out += p[1:]
    assert pkts[-1][0] & 0x40 and not any(p[0] & 0x40 for p in pkts[:-1])
    return out


