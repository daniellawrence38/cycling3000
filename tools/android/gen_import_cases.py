#!/usr/bin/env python3
"""Generates android/app/src/androidTest/kotlin/cc700/app/ImportErrorsTest.kt from the V§4 invalid rows in
android/core/src/test/resources/vectors.json (brief WP6: instrumented UI tests cover the import errors).

Usage, from the repository root: python3 tools/android/gen_import_cases.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VECTORS = os.path.join(ROOT, "android/core/src/test/resources/vectors.json")
OUT = os.path.join(ROOT, "android/app/src/androidTest/kotlin/cc700/app/ImportErrorsTest.kt")


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main():
    d = json.load(open(VECTORS, encoding="utf-8"))
    rows = []
    for r in d["invalid"]:
        text = json.dumps(r["doc"], ensure_ascii=False)
        rows.append(f'            Case({kstr(r["name"])}, {kstr(text)}, {kstr(r["code"])}, {kstr(r["path"])}),')
    w1 = json.dumps(d["w1"]["doc"], ensure_ascii=False)
    src = TEMPLATE.replace("@W1@", kstr(w1)).replace("@CASES@", "\n".join(rows))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"{len(rows)} cases -> {os.path.relpath(OUT, ROOT)}")


