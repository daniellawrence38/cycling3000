#!/usr/bin/env python3
"""Generates the LVGL bitmap fonts the UI uses (brief 6.2), and only those.

Font symbols in ui/src are named font_<f><weight>_<size>: f is 'b' for Barlow and 'c' for Barlow
Condensed, for example font_b600_15 or font_c700_96. This script finds every such symbol in ui/src,
converts each with lv_font_conv (4 bits per pixel) from the Fontsource WOFF files (OFL) and writes
ui/fonts/gen/<symbol>.c plus ui/fonts/fonts.h, and prints the flash cost.

Glyphs: printable ASCII plus · – − … ° ×. Condensed sizes of 44 px and above get only digits,
. : - + space and the minus sign. The arrow → is not in the Barlow files Fontsource ships, so it is
left out (QUESTIONS Q20); no mockup uses it as text.
"""
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
NODE = os.path.join(ROOT, 'build', 'deps', 'node', 'node_modules')
CONV = os.path.join(NODE, '.bin', 'lv_font_conv')
OUT = os.path.join(ROOT, 'ui', 'fonts', 'gen')
EXTRA = '0xB0,0xB7,0xD7,0x2013,0x2026,0x2212'
LARGE_SET = '0x20,0x2B,0x2D,0x2E,0x30-0x3A,0x6B,0x6D,0x2212'  # k and m: "250 m", "1.2 km" on the Navigation banner

def used():
    names = set()
    for p in glob.glob(os.path.join(ROOT, 'ui', 'src', '*.[ch]')) + glob.glob(os.path.join(ROOT, 'ui', 'sim', '*.[ch]')):
        names |= set(re.findall(r'\bfont_([bc])(500|600|700)_(\d+)\b', open(p).read()))
    return sorted(names, key=lambda t: (t[0], int(t[1]), int(t[2])))

def main():
    if not os.path.exists(CONV):
        sys.exit('run ui/deps.sh first')
    os.makedirs(OUT, exist_ok=True)
    fonts = used()
    keep = set()
    total = 0
    for fam, w, size in fonts:
        name = f'font_{fam}{w}_{size}'
        keep.add(name + '.c')
        folder = 'barlow' if fam == 'b' else 'barlow-condensed'
        src = os.path.join(NODE, '@fontsource', folder, 'files', f'{folder}-latin-{w}-normal.woff')
        ranges = ['-r', LARGE_SET] if fam == 'c' and int(size) >= 44 else ['-r', '0x20-0x7E', '-r', EXTRA]
        dst = os.path.join(OUT, name + '.c')
        subprocess.run([CONV, '--font', src, *ranges, '--size', size, '--bpp', '4', '--format', 'lvgl',
                        '--lv-include', 'lvgl.h', '--lv-font-name', name, '-o', dst], check=True)
        # strip the absolute path lv_font_conv records in its header comment
        txt = open(dst).read().replace(NODE + '/', '')
        open(dst, 'w').write(txt)
        m = re.search(r'static (?:LV_ATTRIBUTE_LARGE_CONST )?const uint8_t glyph_bitmap\[\] = \{(.*?)\};', txt, re.S)
        total += len(re.findall(r'0x[0-9a-f]{2}', m.group(1))) if m else 0
    for f in os.listdir(OUT):
        if f.endswith('.c') and f not in keep:
            os.remove(os.path.join(OUT, f))
    with open(os.path.join(ROOT, 'ui', 'fonts', 'fonts.h'), 'w') as h:
        h.write('/* Generated by ui/fonts/gen_fonts.py. Barlow and Barlow Condensed, SIL OFL 1.1. */\n')
        h.write('#ifndef CC700_FONTS_H\n#define CC700_FONTS_H\n#include "lvgl.h"\n\n')
        for fam, w, size in fonts:
            h.write(f'LV_FONT_DECLARE(font_{fam}{w}_{size})\n')
        h.write('\n#endif\n')
    print(f'{len(fonts)} fonts, {total} bytes of glyph bitmaps')

if __name__ == '__main__':
    main()
