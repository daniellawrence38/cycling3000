#!/usr/bin/env python3
"""Renders the mockup icons (icons.json: the same SVG paths, sizes and stroke widths as the boards)
white on transparent with Playwright, and writes their alpha channel as LVGL A8 images in icons.c and
icons.h. Each icon is ic_<name>_<w> (or ic_<name>_<w>x<h> when not square) and is recoloured with
lv_obj_set_style_image_recolor. Needs Node with Playwright and Pillow."""
import json
import os
import subprocess
import sys
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
spec = json.load(open(os.path.join(HERE, 'icons.json')))
tmp = tempfile.mkdtemp()
jobs = []
for name, w, h, sw, mode in spec['icons']:
    sym = f'ic_{name}_{w}' if w == h else f'ic_{name}_{w}x{h}'
    paint = 'fill="#fff" stroke="none"' if mode == 'fill' else f'fill="none" stroke="#fff" stroke-width="{sw}"'
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 24 24" {paint} '
           f'stroke-linecap="round" stroke-linejoin="round">{spec["paths"][name]}</svg>')
    jobs.append(dict(sym=sym, w=w, h=h, svg=svg, png=os.path.join(tmp, sym + '.png')))
json.dump(jobs, open(os.path.join(tmp, 'jobs.json'), 'w'))
js = r"""
const { chromium } = require('playwright');
const jobs = require(process.argv[2]);
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ deviceScaleFactor: 1 });
  for (const j of jobs) {
    await p.setContent(`<html><body style="margin:0;background:transparent">${j.svg}</body></html>`);
    await p.screenshot({ path: j.png, clip: { x: 0, y: 0, width: j.w, height: j.h }, omitBackground: true });
  }
  await b.close();
})();
"""
open(os.path.join(tmp, 'r.js'), 'w').write(js)
env = dict(os.environ, NODE_PATH=subprocess.check_output(['npm', 'root', '-g'], text=True).strip())
subprocess.run(['node', os.path.join(tmp, 'r.js'), os.path.join(tmp, 'jobs.json')], check=True, env=env)

c = ['/* Generated by ui/icons/gen_icons.py from icons.json (paths from the CC700 mockups). A8 alpha. */',
     '#include "icons.h"', '']
h = ['/* Generated by ui/icons/gen_icons.py. */', '#ifndef CC700_ICONS_H', '#define CC700_ICONS_H',
     '#include "lvgl.h"', '']
for j in jobs:
    a = Image.open(j['png']).convert('RGBA').split()[3]
    data = list(a.getdata())
    rows = [', '.join(f'0x{v:02x}' for v in data[i:i + j['w']]) for i in range(0, len(data), j['w'])]
    c.append(f'static const uint8_t {j["sym"]}_map[] = {{\n    ' + ',\n    '.join(rows) + '\n};')
    c.append(f'const lv_image_dsc_t {j["sym"]} = {{\n    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, '
             f'.cf = LV_COLOR_FORMAT_A8, .w = {j["w"]}, .h = {j["h"]}, .stride = {j["w"]}}},\n'
             f'    .data_size = sizeof({j["sym"]}_map),\n    .data = {j["sym"]}_map,\n}};\n')
    h.append(f'extern const lv_image_dsc_t {j["sym"]};')
h += ['', '#endif', '']
open(os.path.join(HERE, 'icons.c'), 'w').write('\n'.join(c))
open(os.path.join(HERE, 'icons.h'), 'w').write('\n'.join(h))
print(len(jobs), 'icons')
